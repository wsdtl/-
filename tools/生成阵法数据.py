def stage_rows(profile: tuple[float, ...], scale: float) -> list[dict[str, float | int]]:
    threshold = profile[:3]
    cycle = profile[3:6]
    impact = profile[6:]
    rows = [{"阶段": 1, "环境阶段阈值倍率": 1.0, "行动周期倍率": 1.0, "阵势倍率": 1.0}]
    for index in range(3):
        rows.append(
            {
                "阶段": index + 2,
                "环境阶段阈值倍率": round(1 + threshold[index] * scale, 4),
                "行动周期倍率": round(1 + cycle[index] * scale, 4),
                "阵势倍率": round(1 + impact[index] * scale, 4),
            }
        )
    return rows


def build_grade(profile: tuple[object, ...], tier: str, cost_scale: int, strength_scale: float) -> dict[str, object]:
    _, _monitor, _core, weights, cost, base, node, curve = profile
    base_cost = dict(zip(("兽宝", "灵矿", "灵植"), cost, strict=True))
    if tier == "圣":
        return {
            "品级": "圣",
            "最低消耗": {key: value * 81 for key, value in base_cost.items()},
            "阵基": {"基础承载": int(base[0] * SAINT_BASE_SCALE)},
            "阵眼": {"基础冲击": int(base[1] * SAINT_BASE_SCALE)},
            "节点": {
                "起始数量": max(1, int(node[0] * SAINT_BASE_SCALE)),
                "名称": node[1],
                "基础传导": round(SAINT_BASE_SCALE, 4),
            },
            "圣品权重": {"阵基": weights[0], "阵眼": weights[1], "节点": weights[2]},
            "地势阶段": stage_rows(curve, SAINT_BASE_SCALE),
        }
    return {
        "品级": tier,
        "消耗": {key: value * cost_scale for key, value in base_cost.items()},
        "阵基": {"承载": int(base[0] * strength_scale)},
        "阵眼": {"冲击": int(base[1] * strength_scale)},
        "节点": {"数量": max(1, int(node[0] * strength_scale)), "名称": node[1], "传导": round(strength_scale, 4)},
        "地势阶段": stage_rows(curve, strength_scale),
    }


def build() -> list[dict[str, object]]:
    output: list[dict[str, object]] = []
    for index, profile in enumerate(PROFILES, start=1):
        grades = [build_grade(profile, tier, cost_scale, strength_scale) for tier, cost_scale, strength_scale in TIERS]
        grades.append(build_grade(profile, "圣", 81, SAINT_BASE_SCALE))
        output.append(
            {
                "编号": f"530{index:03d}",
                "名称": profile[0],
                "宏观监测": list(profile[1]),
                "阵法核心": profile[2],
                "品级": grades,
            }
        )
    return output


def validate(formations: list[dict[str, object]]) -> None:
    if len(formations) != 46:
        raise ValueError(f"阵法数量必须为 46，当前为 {len(formations)}")

    unique_fields = {
        "编号": [formation["编号"] for formation in formations],
        "名称": [formation["名称"] for formation in formations],
        "宏观监测": [tuple(formation["宏观监测"]) for formation in formations],
        "阵法核心": [formation["阵法核心"] for formation in formations],
    }
    for field, values in unique_fields.items():
        if len(values) != len(set(values)):
            raise ValueError(f"阵法{field}存在重复")

    weights: set[tuple[float, float, float]] = set()
    curves: set[str] = set()
    for formation in formations:
        grades = formation["品级"]
        if [grade["品级"] for grade in grades] != ["黄", "玄", "地", "天", "圣"]:
            raise ValueError(f"{formation['名称']}的品级顺序不完整")

        saint = grades[-1]
        weight = tuple(saint["圣品权重"].values())
        if abs(sum(weight) - 3) > 1e-9:
            raise ValueError(f"{formation['名称']}的圣品权重和不为 3")
        if weight in weights:
            raise ValueError(f"{formation['名称']}的圣品权重与其他阵法重复")
        weights.add(weight)

        curve = json.dumps(saint["地势阶段"], ensure_ascii=False, sort_keys=True)
        if curve in curves:
            raise ValueError(f"{formation['名称']}的地势曲线与其他阵法重复")
        curves.add(curve)

        tian = grades[-2]
        if saint["阵基"]["基础承载"] <= tian["阵基"]["承载"]:
            raise ValueError(f"{formation['名称']}的圣品阵基不高于天品")
        if saint["阵眼"]["基础冲击"] <= tian["阵眼"]["冲击"]:
            raise ValueError(f"{formation['名称']}的圣品阵眼不高于天品")
        if saint["节点"]["起始数量"] <= tian["节点"]["数量"]:
            raise ValueError(f"{formation['名称']}的圣品节点不高于天品")

        for grade in grades:
            stages = grade["地势阶段"]
            if [stage["阶段"] for stage in stages] != [1, 2, 3, 4]:
                raise ValueError(f"{formation['名称']}的地势阶段不完整")
            for stage in stages:
                values = (
                    stage["环境阶段阈值倍率"],
                    stage["行动周期倍率"],
                    stage["阵势倍率"],
                )
                if any(value <= 0 for value in values):
                    raise ValueError(f"{formation['名称']}存在非正地势倍率")


